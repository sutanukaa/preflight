import crypto from 'node:crypto';
import { db } from '../db/db.js';
import { dnsInspector } from './dns-resolver.js';
import { mergeSpfRecord } from '@preflight/shared';
import { getDmarcProgression } from '@preflight/shared';
import type { FixProposal, VerificationRun } from '@preflight/shared';

export class FixProposalService {
  /**
   * Generates a safe DNS fix proposal for a specific check finding.
   */
  async generateFixProposal(findingCheckId: string): Promise<FixProposal | null> {
    // Look up check from DB or memory
    let check: Record<string, unknown> | null = null;
    if (db.memory) {
      check = db.memory.getTable('checks').get(findingCheckId) || null;
    }

    // If check not in db table directly, search within reports
    if (!check) {
      // Fallback check generator based on key prefix
      const key = findingCheckId.split('_')[1] || 'dmarc';
      check = { id: findingCheckId, key: `${key}_record`, status: 'warning', domain_id: 'dom_acme_studio' };
    }

    const domain = (await db.getDomainById(String(check.domain_id || 'dom_acme_studio'))) || { fqdn: 'acme.studio' };
    const domainName = String(domain.fqdn);
    const key = String(check.key || '');
    const proposalId = 'fix_' + crypto.randomUUID().replace(/-/g, '');

    if (key.includes('spf')) {
      const txts = await dnsInspector['resolver'].resolveTxt(domainName);
      const currentSpf = txts.find(t => t.toLowerCase().startsWith('v=spf1')) || null;
      const merged = mergeSpfRecord(currentSpf, '~all');

      const proposal: FixProposal = {
        id: proposalId,
        findingCheckId,
        recordType: 'TXT',
        recordHost: domainName,
        currentValue: currentSpf,
        proposedValue: merged.proposedRecord,
        rationale: merged.note,
        warning: 'Ensure all authorized outbound sending IP addresses and services are included before switching from ~all to -all.',
        state: 'proposed',
        createdAt: new Date().toISOString()
      };

      await db.createFixProposal({
        id: proposal.id,
        finding_check_id: proposal.findingCheckId,
        record_type: proposal.recordType,
        record_name: proposal.recordHost,
        proposed_value: proposal.proposedValue,
        rationale: proposal.rationale,
        state: proposal.state
      });

      return proposal;
    }

    if (key.includes('dmarc')) {
      const dmarcTxts = await dnsInspector['resolver'].resolveTxt(`_dmarc.${domainName}`);
      const currentDmarc = dmarcTxts.find(t => t.toLowerCase().startsWith('v=dmarc1')) || null;
      const progression = getDmarcProgression(currentDmarc, domainName);

      const proposal: FixProposal = {
        id: proposalId,
        findingCheckId,
        recordType: 'TXT',
        recordHost: `_dmarc.${domainName}`,
        currentValue: currentDmarc,
        proposedValue: progression.recommendedRecord,
        rationale: `${progression.nextStepName}: ${progression.rationale}`,
        warning: progression.warningNotice,
        state: 'proposed',
        createdAt: new Date().toISOString()
      };

      await db.createFixProposal({
        id: proposal.id,
        finding_check_id: proposal.findingCheckId,
        record_type: proposal.recordType,
        record_name: proposal.recordHost,
        proposed_value: proposal.proposedValue,
        rationale: proposal.rationale,
        state: proposal.state
      });

      return proposal;
    }

    if (key.includes('dkim')) {
      const proposal: FixProposal = {
        id: proposalId,
        findingCheckId,
        recordType: 'TXT',
        recordHost: `selector1._domainkey.${domainName}`,
        currentValue: null,
        proposedValue: 'v=DKIM1; k=rsa; p=<your-public-key-from-email-provider>',
        rationale: 'DKIM public keys must be generated by your email sending provider (Google Workspace, Postmark, SendGrid). Preflight will never fabricate cryptographic key material.',
        warning: 'Copy the exact public key string from your sending provider admin console.',
        state: 'proposed',
        createdAt: new Date().toISOString()
      };

      await db.createFixProposal({
        id: proposal.id,
        finding_check_id: proposal.findingCheckId,
        record_type: proposal.recordType,
        record_name: proposal.recordHost,
        proposed_value: proposal.proposedValue,
        rationale: proposal.rationale,
        state: proposal.state
      });

      return proposal;
    }

    return null;
  }

  /**
   * Verifies whether a proposed DNS record has propagated.
   */
  async verifyProposal(proposalId: string): Promise<VerificationRun> {
    const proposal = await db.getFixProposalById(proposalId);
    if (!proposal) {
      throw new Error('PROPOSAL_NOT_FOUND');
    }

    const host = String(proposal.record_name || proposal.recordHost);
    const expected = String(proposal.proposed_value || proposal.proposedValue);
    const records = await dnsInspector['resolver'].resolveTxt(host);
    const matched = records.some(r => r.trim() === expected.trim());

    const run: VerificationRun = {
      id: 'run_' + crypto.randomUUID().replace(/-/g, ''),
      fixProposalId: proposalId,
      state: matched ? 'verified' : 'failed',
      attempts: 1,
      lastObservedValue: records.join(' | ') || null,
      completedAt: new Date().toISOString()
    };

    if (matched) {
      await db.updateFixProposal(proposalId, { state: 'verified' });
    }

    return run;
  }
}

export const fixProposalService = new FixProposalService();
